    print(row_fmt.format(*headers))
    print(sep_fmt.format("-" * 10, "-" * 18, "-" * 10, "-" * 8, "-" * 9))
    for r in results:
        print(row_fmt.format(r["tree"], r["suite"], r["tests_run"], r["result"], str(r["exit_code"])))

