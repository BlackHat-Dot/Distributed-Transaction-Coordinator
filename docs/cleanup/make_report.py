def check_redis(host="127.0.0.1", port=6379, timeout=2.0):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except Exception:
        return False

def run_suite(tree_path, rel_manage, suite_arg):
    manage_py = os.path.join(tree_path, *rel_manage)
    cmd = [sys.executable, manage_py, "test", suite_arg, "--noinput"]
    proc = subprocess.run(
        cmd,
        cwd=tree_path,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    output = proc.stdout
    retcode = proc.returncode

    match_ran = re.search(r"Ran (\d+) tests", output)
    test_count = match_ran.group(1) if match_ran else "Unknown"

    after_ran = output[match_ran.start():] if match_ran else output
    if re.search(r"^FAILED", after_ran, re.MULTILINE) or retcode != 0:
        result = "FAILED"
    elif re.search(r"^OK", after_ran, re.MULTILINE):
        result = "OK"
    else:
        result = "UNKNOWN"

    timeout_count = output.count("Timeout connecting to server")
    return test_count, result, retcode, timeout_count, output

